// police.mjs — POLICE BITMAP 5×8, écrite à la main.
//
// Une image que l'on doit deviner est une image ratée : les planches portent
// donc leur propre légende (nom du clip, instants, échelle, axes). Il faut donc
// savoir écrire du texte dans un tampon de pixels, et aucune dépendance n'est
// permise. D'où cette police.
//
// Chaque glyphe est déclaré en ASCII-art — 5 colonnes, 7 lignes utiles (0..6)
// plus une 8ᵉ ligne (7) réservée aux jambages (g j p q y) et à la cédille.
// Le déclarer en dessin plutôt qu'en hexadécimal est le seul moyen de le
// RELIRE : une erreur de bit se voit à l'œil dans le source.
//
// Les accents sont composés à la volée (lettre de base + signe posé sur les
// lignes 0-1, qui sont vides pour les minuscules). Les majuscules accentuées
// retombent sur la lettre nue : il n'y a pas la place, et « ECART » se lit.
// ════════════════════════════════════════════════════════════════════════════

