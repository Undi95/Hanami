/** Convertit un dessin ASCII-art en masques de lignes (bit 0 = colonne de gauche). */
function compiler(lignes) {
  const m = new Uint8Array(HAUTEUR)
  for (let y = 0; y < Math.min(lignes.length, HAUTEUR); y++) {
    let bits = 0
    for (let x = 0; x < LARGEUR; x++) if (lignes[y][x] === '#') bits |= 1 << x
    m[y] = bits
  }
  return m
}

const CACHE = new Map()
for (const [c, d] of Object.entries(DESSINS)) CACHE.set(c, compiler(d))
const SIGNES_C = Object.fromEntries(Object.entries(SIGNES).map(([k, v]) => [k, compiler(v)]))

/**
 * Masques de lignes d'un caractère (Uint8Array de HAUTEUR entrées).
 * Compose les accents à la demande et met le résultat en cache.
 */
export function glyphe(c) {
  const t = CACHE.get(c)
  if (t) return t
  if (ACCENTUEES[c]) {
    const [base, signe] = ACCENTUEES[c]
    const b = CACHE.get(base)
    const m = new Uint8Array(HAUTEUR)
    m.set(b)
    m[0] = SIGNES_C[signe][0]
    m[1] = SIGNES_C[signe][1]
    // « i » et « ï » : le point de l'i doit céder la place au signe.
    if (base === 'i' || base === 'j') m[0] = SIGNES_C[signe][0]
    CACHE.set(c, m)
    return m
  }
  if (c === 'ç') {
    const m = new Uint8Array(HAUTEUR)
    m.set(CACHE.get('c'))
    m[7] = 0b00100 // cédille
    CACHE.set(c, m)
    return m
  }
  const r = REPLIS[c]
  if (r) { const m = glyphe(r); CACHE.set(c, m); return m }
  return CACHE.get('?')
}

/** Largeur en pixels d'une chaîne rendue à l'échelle donnée. */
export function largeurTexte(s, echelle = 1) {
  return s.length === 0 ? 0 : (s.length * AVANCE - 1) * echelle
}
