// Consigne d'ouverture (mode 'open') — même statut : elle vit dans le payload, jamais
// dans le fichier de chat. Le personnage parle donc en premier depuis son seul system
// prompt (system vide = personnalité par défaut du modèle).
const OPEN_DIRECTIVE =
  '[Open the conversation with a short, natural in-character first message to the user. Do not mention this instruction.]'

// Images du message courant : plafonds volontairement bas — on parle d'un chat,
// pas d'un dépôt de fichiers (le client redimensionne déjà avant l'envoi).
const MAX_IMAGES = 4
const MAX_IMAGE_CHARS = 2 * 1024 * 1024 // ~2 Mo par data URL (donc après encodage base64)
const DATA_IMAGE_RE = /^data:image\/(png|jpe?g|webp);base64,/

/** Valide body.images : uniquement des data URLs d'image, plafonnées en nombre et en poids. */
function parseImages(raw: unknown): { images: string[] } | { error: string; status: number } {
  if (raw === undefined || raw === null) return { images: [] }
  if (!Array.isArray(raw)) return { error: 'images doit être un tableau de data URLs', status: 400 }
  if (raw.length > MAX_IMAGES) {
    return { error: `Trop d'images (maximum ${MAX_IMAGES})`, status: 413 }
  }
  const images: string[] = []
  for (const item of raw) {
    if (typeof item !== 'string' || !DATA_IMAGE_RE.test(item)) {
      return { error: 'Chaque image doit être une data URL image/png, image/jpeg ou image/webp', status: 400 }
    }
    if (item.length > MAX_IMAGE_CHARS) {
      return { error: `Image trop lourde (maximum ~${Math.round(MAX_IMAGE_CHARS / 1024 / 1024)} Mo)`, status: 413 }
    }
    images.push(item)
  }
  return { images }
}

/**
 * Boucle agentique PARTAGÉE entre le chat (streaming SSE) et la compaction
 * (silencieuse) — avant cette factorisation, les deux copies vivaient chacune
 * leur vie. Elle fait UNIQUEMENT la mécanique commune : appeler le modèle,
 * tracer fidèlement l'aller-retour d'outils dans `messages` (assistant avec
 * tool_calls, puis un message tool par exécution), et — budget épuisé alors
 * que le modèle en redemande — un dernier appel SANS outils pour obtenir la
 * réponse finale. Tout le reste (streaming, événements SSE, agrégation de
 * finishReason/promptTokens) appartient à l'appelant, via la fermeture de
 * `call` et le crochet `onTool`.
 */
/** Noms des outils réellement annoncés dans un tableau de définitions OpenAI. */
function toolNamesOf(tools: unknown[] | undefined): ReadonlySet<string> {
  const names = new Set<string>()
  for (const t of tools ?? []) {
    const name = (t as { function?: { name?: unknown } }).function?.name
    if (typeof name === 'string' && name) names.add(name)
  }
  return names
}

async function runToolLoop<R extends { content: string; toolCalls: StreamedToolCall[] }>(
  characterId: string,
  settings: Settings,
  messages: unknown[],
  maxIterations: number,
  // Seuls les outils ANNONCÉS dans la requête sont exécutables : un nom
  // halluciné (ou hors du périmètre de la compaction) devient une erreur
  // d'outil rendue au modèle, jamais une exécution.
  allowed: ReadonlySet<string>,
  // Fichiers mémoire lus pendant CETTE requête — le garde-fou « lire avant
  // d'écrire » de memoryTools s'appuie dessus.
  mem: MemorySession,
  call: (withTools: boolean) => Promise<R>,
  onTool?: (name: string, args: string, result: string) => void,
  onToolStart?: (name: string, args: string) => void,
): Promise<{ last: R; exhausted: boolean }> {
  let last = await call(true)
  for (let iteration = 1; ; iteration++) {
    if (last.toolCalls.length === 0) return { last, exhausted: false }
    // Trace fidèle de l'aller-retour outil dans le contexte de la boucle.
    messages.push({
      role: 'assistant',
      content: last.content || null,
      tool_calls: last.toolCalls.map((tc) => ({
        id: tc.id,
        type: 'function',
        function: { name: tc.name, arguments: tc.arguments },
      })),
    })
    for (const tc of last.toolCalls) {
      let toolResult: string
      if (!allowed.has(tc.name)) {
        toolResult = `Error: tool not offered in this request: ${tc.name}`
      } else {
        // Signalé AVANT l'exécution : l'interface anime la puce pendant
        // l'action (sans elle, le fil semble figé tant que le modèle
        // n'a pas « fini » de parler).
        onToolStart?.(tc.name, tc.arguments)
        try {
          toolResult = await executeTool(characterId, settings, tc.name, tc.arguments, mem)
        } catch (e) {
          toolResult = `Error: ${e instanceof Error ? e.message : String(e)}`
        }
      }
      onTool?.(tc.name, tc.arguments, toolResult)
      messages.push({ role: 'tool', tool_call_id: tc.id, content: toolResult })
    }
    if (iteration >= maxIterations) {
      // Budget épuisé, le modèle veut encore des outils : réponse finale sans eux.
      return { last: await call(false), exhausted: true }
    }
    last = await call(true)
  }
}

async function handleChat(req: Request, res: Response): Promise<void> {
  const body = (req.body ?? {}) as {
    characterId?: unknown
    chatId?: unknown
    content?: unknown
    images?: unknown
    mode?: unknown
    forceSearch?: unknown
  }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const content = typeof body.content === 'string' ? body.content : ''
  // /search du composer : force une recherche web AVANT le premier appel au
  // modèle (voir plus bas), au lieu de compter sur le modèle pour décider d'y
  // recourir. Sans effet hors message normal (mode défini, ou recherche web
  // désactivée/indisponible) — /search dégrade alors en simple message.
  const forceSearch = body.forceSearch === true
  const mode =
    body.mode === 'regenerate' || body.mode === 'continue' || body.mode === 'open' || body.mode === 'impersonate'
      ? body.mode
      : undefined
  // Validé avant toute autre chose : la réponse est encore du JSON à ce stade
  // (une fois le flux SSE ouvert, plus aucun code d'erreur HTTP n'est possible).
  const parsedImages = parseImages(body.images)
  if ('error' in parsedImages) {
    res.status(parsedImages.status).json({ error: parsedImages.error })
    return
  }
  // Les images n'appartiennent qu'au message COURANT : régénérer/continuer/ouvrir
  // rejoue l'historique, qui porte déjà les siennes.
  const images = mode ? [] : parsedImages.images
  // Une image seule est un message légitime (le texte peut être vide).
  if (!characterId || !chatId || (!content && !mode && images.length === 0)) {
    res.status(400).json({ error: 'characterId, chatId et content (ou images, ou mode) sont requis' })
    return
  }
  const settings = loadSettings()
  if (!getCharacter(characterId)) {
    res.status(404).json({ error: `Personnage introuvable : ${characterId}` })
    return
  }
  let existing: ChatMessage[]
  try {
    existing = readChat(characterId, chatId).messages
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }

  // Base d'une continuation : le dernier message assistant, complété en place.
  let continueBase: ChatMessage | null = null
  // Base d'une régénération : la réponse actuelle, qui NE SORT PAS du fichier —
  // elle deviendra une variante du même message une fois la nouvelle écrite.
  let regenBase: ChatMessage | null = null
  // Régénérer un premier message généré : la conversation redevient vide, le payload
  // reprend donc la consigne d'ouverture (sinon le modèle n'aurait aucun tour user).
  let regenOpens = false
  if (mode === 'regenerate') {
    if (existing.length === 0) {
      res.status(400).json({ error: 'Rien à régénérer (conversation vide)' })
      return
    }
    // Dernier message = réponse de l'assistant → nouvelle VARIANTE de ce message.
    // Le fichier n'est pas touché ici : la réponse actuelle est seulement retirée
    // de l'historique envoyé (omitLastMessage), et l'épingle — qui vise un
    // message toujours présent, au même rang — n'a plus de raison d'être levée.
    // (Dernier message = user, ex. génération précédente échouée → on rejoue tel quel.)
    if (existing[existing.length - 1].role === 'assistant') {
      regenBase = existing[existing.length - 1]
      regenOpens = existing.length === 1
    }
  } else if (mode === 'continue') {
    const last = existing[existing.length - 1]
    if (!last || last.role !== 'assistant') {
      res.status(400).json({ error: 'Rien à continuer (le dernier message n’est pas une réponse)' })
      return
    }
    continueBase = last
  } else if (mode === 'open' && existing.length > 0) {
    // Le premier message ne se génère que dans une conversation encore vierge.
    res.status(400).json({ error: "La conversation n'est pas vide (rien à ouvrir)" })
    return
  } else if (mode === 'impersonate' && existing.length === 0) {
    // Impersonate a besoin d'au moins un tour à imiter (ton, longueur, sujet).
    res.status(400).json({ error: 'Rien à impersonner (conversation vide)' })
    return
  }

  // Payload construit AVANT la sauvegarde : le message courant passe par pendingUserContent,
  // sinon il consommerait un slot d'historique (et ne serait jamais envoyé si
  // maxHistoryMessages = 0).
  const pendingUser: string | ContentPart[] | undefined =
    mode === 'continue'
      ? CONTINUE_DIRECTIVE
      : mode === 'open' || regenOpens
        ? OPEN_DIRECTIVE
        : mode === 'regenerate' || mode === 'impersonate'
          ? undefined
          : images.length > 0
            ? multimodalContent(content, images)
            : content
  // Impersonate ne passe JAMAIS par buildPayload : son system prompt et son
  // historique (rôles échangés) sont d'une nature différente — voir buildImpersonatePayload.
  const { payload } =
    mode === 'impersonate'
      ? buildImpersonatePayload(characterId, chatId, settings)
      : buildPayload(characterId, chatId, settings, pendingUser, regenBase !== null)
  const messages = payload.messages as Record<string, unknown>[]

  // Le message user est sauvegardé AVANT l'appel backend : il survit à toute erreur en aval.
  if (!mode) {
    // Le fil AVANCE : les variantes non affichées de la réponse précédente sont
    // élaguées (cf. pruneVariants). Aucun message n'entre ni ne sort — les
    // repères qui comptent des messages (épingle, summaryUpto) ne bougent pas.
    if (existing.some((m) => m.variants !== undefined)) {
      rewriteChatMessages(characterId, chatId, (msgs) => msgs.map(pruneVariants))
    }
    const userMsg: ChatMessage = { role: 'user', content, ts: new Date().toISOString() }
    if (images.length > 0) userMsg.images = images
    appendChatMessage(characterId, chatId, userMsg)
  }

  res.setHeader('Content-Type', 'text/event-stream')
  res.setHeader('Cache-Control', 'no-cache')
  res.setHeader('Connection', 'keep-alive')
  res.flushHeaders()

  const abort = new AbortController()
  // Déconnexion client en plein stream → on coupe l'appel backend.
  // res 'close' + writableEnded, car req 'close' se déclenche dès la fin du body en Node ≥ 15.
  res.on('close', () => {
    if (!res.writableEnded) abort.abort()
  })

  // Recherche forcée AVANT tout appel au modèle — un aller-retour d'outil
  // authentique (assistant tool_calls + tool) est inséré dans `messages`,
  // exactement comme si le modèle avait choisi d'appeler l'outil lui-même.
  // « Forcer » veut dire ne pas dépendre de sa décision : le modèle garde la
  // main pour chercher PLUS s'il le juge utile (l'outil reste exposé).
  // Deux déclencheurs : /search explicite (tout `content` = la requête), ou —
  // filet indépendant du modèle — une intention de recherche EXPLICITE
  // détectée dans un message normal (« cherche sur le web… », « google it »…) :
  // certains modèles préfèrent « jouer » la recherche en roleplay plutôt que
  // d'appeler l'outil ; ce filet la garantit quand même.
  // Journal d'activité de la génération : chaque action exécutée y est notée,
  // puis rattachée au message persisté (l'affichage en fait les puces — jamais
  // renvoyé au backend, cf. shared/types.ts).
  const toolTraces: ToolTrace[] = []

  const trimmedContent = content.trim()
  const forcedQuery = forceSearch
    ? trimmedContent
    : !mode && trimmedContent
      ? detectSearchIntent(trimmedContent)
      : null
  if (!mode && forcedQuery && settings.webSearchEnabled && settings.modelMode !== 'simple') {
    const query = forcedQuery
    const toolCallId = `search_${Date.now()}`
    const searchArgs = JSON.stringify({ query })
    writeEvent(res, { type: 'tool_start', name: 'web_search', args: searchArgs })
    let result: string
    try {
      result = await executeWebSearchTool(settings, { query })
    } catch (e) {
      result = `Erreur : ${e instanceof Error ? e.message : String(e)}`
    }
    messages.push({
      role: 'assistant',
      content: null,
      tool_calls: [{ id: toolCallId, type: 'function', function: { name: 'web_search', arguments: searchArgs } }],
    })
    messages.push({ role: 'tool', tool_call_id: toolCallId, content: result })
    toolTraces.push({ name: 'web_search', args: searchArgs, result: cappedTraceResult(result) })
    writeEvent(res, { type: 'tool', name: 'web_search', args: searchArgs, result })
  }

  let assistantText = ''
  let assistantThinking = ''

  // Un appel streaming. Entre deux itérations, un séparateur "\n\n" est inséré dans le texte
  // ET émis comme delta : le flux affiché et le texte sauvegardé restent identiques.
  const streamOnce = (withTools: boolean) => {
    let firstDelta = true
    let firstThinking = true
    return streamChatCompletion({
      settings,
      messages,
      tools: withTools ? payload.tools : undefined,
      signal: abort.signal,
      onDelta: (text) => {
        if (firstDelta) {
          firstDelta = false
          if (assistantText.length > 0) {
            assistantText += '\n\n'
            writeEvent(res, { type: 'delta', text: '\n\n' })
          }
        }
        assistantText += text
        writeEvent(res, { type: 'delta', text })
      },
      onThinking: (text) => {
        if (firstThinking) {
          firstThinking = false
          if (assistantThinking.length > 0) assistantThinking += '\n\n'
        }
        assistantThinking += text
        writeEvent(res, { type: 'thinking', text })
      },
    })
  }

  // Sauvegarde de la sortie : continuation → fusionnée dans le dernier message
  // assistant (en place, timestamp d'origine conservé) ; sinon → message ajouté.
  // La fusion vérifie l'IDENTITÉ du message visé (ts + contenu), pas seulement
  // son rôle : le stream est la seule fenêtre asynchrone du fichier, et un
  // message spontané (même processus) peut s'ajouter pendant qu'il coule —
  // écraser le dernier venu perdrait SON texte. Fil bougé → la continuation
  // est AJOUTÉE en message à part : rien d'écrasé, rien de perdu, et le `done`
  // renvoie ce qui est réellement sur le disque.
  const persistAssistant = (): ChatMessage => {
    if (mode === 'impersonate') {
      // Jamais écrit sur le disque : impersonate ne fait qu'écrire dans le
      // composer du client (à éditer avant envoi) — la conversation elle-même
      // n'avance pas d'un message. `role: 'user'` par cohérence de type
      // seulement, rien n'est lu au-delà de `content` côté client.
      return { role: 'user', content: assistantText, ts: new Date().toISOString() }
    }
    if (mode === 'continue' && continueBase) {
      const base = continueBase
      const joiner = base.content.endsWith('\n') || assistantText.startsWith('\n') ? '' : ' '
      let merged: ChatMessage = { ...base, content: base.content + joiner + assistantText }
      const mergedEmotion = firstEmotionTag(merged.content)
      if (mergedEmotion) merged.emotion = mergedEmotion
      if (assistantThinking) {
        merged.thinking = base.thinking ? base.thinking + '\n\n' + assistantThinking : assistantThinking
      }
      // Les actions de la passée de continuation s'ajoutent au journal de la
      // variante affichée (le corps du message la recopie — cf. invariant).
      if (toolTraces.length > 0) merged.tools = [...(base.tools ?? []), ...toolTraces]
      // Le message porte des variantes : c'est la variante AFFICHÉE qui s'allonge
      // (« Continuer » continue ce qu'on lit) — les autres restent feuilletables.
      const active = merged.variant
      if (merged.variants && typeof active === 'number') {
        const grown = merged.variants.map((v, i) => (i === active ? bodyOf(merged) : v))
        merged = withVariants(merged, grown, active)
      }
      const continued = merged
      let saved: ChatMessage = continued
      rewriteChatMessages(characterId, chatId, (msgs) => {
        const lastMsg = msgs[msgs.length - 1]
        if (lastMsg && lastMsg.role === 'assistant' && lastMsg.ts === base.ts && lastMsg.content === base.content) {
          msgs[msgs.length - 1] = continued
          return msgs
        }
        saved = toAssistantMessage(assistantText, assistantThinking)
        if (toolTraces.length > 0) saved.tools = [...toolTraces]
        msgs.push(saved)
        return msgs
      })
      return saved
    }
    const message = toAssistantMessage(assistantText, assistantThinking)
    if (toolTraces.length > 0) message.tools = [...toolTraces]
    // Régénération : la nouvelle réponse rejoint les précédentes DANS le message,
    // et devient celle qui est affichée. Comme pour la continuation, l'IDENTITÉ
    // du message visé est vérifiée (ts + contenu) : un message spontané a pu
    // s'ajouter pendant le stream — fil bougé, la réponse est alors simplement
    // AJOUTÉE, rien n'est écrasé.
    if (mode === 'regenerate' && regenBase) {
      const base = regenBase
      // Génération VIDE (budget de sortie parti dans le raisonnement, coupure
      // nette) : aucune variante à ajouter — la réponse en place reste, et rien
      // n'est réécrit. Sans ce garde-fou, une variante vide deviendrait la
      // variante affichée et masquerait une bonne réponse derrière une flèche.
      if (assistantText.length === 0) return base
      let saved: ChatMessage = message
      rewriteChatMessages(characterId, chatId, (msgs) => {
        const lastMsg = msgs[msgs.length - 1]
        if (lastMsg && lastMsg.role === 'assistant' && lastMsg.ts === base.ts && lastMsg.content === base.content) {
          const list = [...variantsOf(lastMsg), bodyOf(message)].slice(-MAX_VARIANTS)
          saved = withVariants(lastMsg, list, list.length - 1)
          msgs[msgs.length - 1] = saved
          return msgs
        }
        msgs.push(message)
        return msgs
      })
      return saved
    }
    appendChatMessage(characterId, chatId, message)
    return message
  }

  try {
    let truncated = false
    let finishReason = ''
    let promptTokens = 0

    // Les agrégations (truncated, finishReason, promptTokens — le dernier usage
    // NON NUL fait foi) restent ici, par fermeture : la boucle partagée ne
    // s'occupe que de la mécanique d'outils.
    const mem = createMemorySession() // lectures mémoire de CETTE requête (garde-fou)
    const { exhausted } = await runToolLoop(
      characterId,
      settings,
      messages,
      MAX_TOOL_ITERATIONS,
      toolNamesOf(payload.tools),
      mem,
      async (withTools) => {
        const result = await streamOnce(withTools)
        truncated = result.truncated
        finishReason = result.finishReason
        if (result.promptTokens > 0) promptTokens = result.promptTokens
        return result
      },
      (name, args, toolResult) => {
        writeEvent(res, { type: 'tool', name, args, result: toolResult })
        toolTraces.push({ name, args, result: cappedTraceResult(toolResult) })
      },
      (name, args) => {
        writeEvent(res, { type: 'tool_start', name, args })
      },
    )

    if (exhausted && assistantText.length === 0) {
      // Rien à sauvegarder : pas de message vide, pas de done.
      writeEvent(res, { type: 'error', message: "Budget d'outils épuisé sans réponse du modèle" })
      res.end()
      return
    }

    // Contenu INTÉGRAL, tel que généré (le tag d'émotion reste dans le texte).
    const message = persistAssistant()
    // Jauge de contexte : usage réel du backend quand il le fournit, sinon
    // estimation sur le payload final (qui inclut les allers-retours d'outils
    // ET les définitions d'outils, comptées par l'usage réel elles aussi).
    const tokens =
      (promptTokens > 0 ? promptTokens : estimateTokens(messages) + estimateTokens(payload.tools ?? [])) +
      estimateTokens(assistantText)
    // Fenêtre de TRAVAIL (plafonnée) et non le contexte complet du modèle :
    // avec une fenêtre de 262k, la jauge plafonnait à ~15 % et l'auto-compaction
    // ne se déclenchait jamais (voir workingWindow dans config.ts).
    const limit = workingWindow(settings)
    const context: ContextInfo = {
      tokens,
      limit,
      percent: limit > 0 ? Math.min(100, Math.round((tokens / limit) * 100)) : 0,
    }
    writeEvent(res, { type: 'done', message, context })
    // Signalé APRÈS la sauvegarde et le done : le client affiche la bulle d'erreur discrète.
    if (truncated || finishReason === 'length') {
      writeEvent(res, {
        type: 'error',
        message: truncated
          ? 'Réponse probablement tronquée (flux interrompu avant la fin)'
          : 'Réponse coupée (max_tokens atteint)',
      })
    }
    res.end()
  } catch (e) {
    if (abort.signal.aborted) {
      // Client parti : on sauvegarde le partiel si au moins un delta est arrivé.
      if (assistantText.length > 0) persistAssistant()
      try {
        res.end()
      } catch {
        /* socket déjà fermée */
      }
      return
    }
    const message = e instanceof Error ? e.message : String(e)
    if (assistantText.length > 0) {
      // Erreur mi-flux : le partiel déjà affiché côté client est sauvegardé, et joint à l'événement.
      const partial = persistAssistant()
      writeEvent(res, { type: 'error', message, partial })
    } else {
      writeEvent(res, { type: 'error', message })
    }
    res.end()
  }
}

// Verrou par chat du mode 'open' : le premier message d'une conversation vide
// peut être demandé deux fois (deux appareils ouverts, double clic) et la
// conversation se retrouverait avec DEUX ouvertures empilées.
const opensInFlight = new Set<string>()

chatRouter.post('/api/chat', async (req, res) => {
  // Verrou posé AVANT handleChat : dès que le flux SSE est ouvert, plus aucun
  // code d'erreur HTTP n'est possible.
  const body = (req.body ?? {}) as { characterId?: unknown; chatId?: unknown; mode?: unknown }
  const openKey =
    body.mode === 'open' && typeof body.characterId === 'string' && typeof body.chatId === 'string'
      ? `${body.characterId}/${body.chatId}`
      : null
  if (openKey !== null) {
    if (opensInFlight.has(openKey)) {
      res.status(409).json({ error: 'Ouverture déjà en cours pour cette conversation' })
      return
    }
    opensInFlight.add(openKey)
  }
  try {
    await handleChat(req, res)
  } catch (e) {
    // Dernier filet (ne devrait pas arriver : handleChat gère ses erreurs).
    const message = e instanceof Error ? e.message : String(e)
    if (!res.headersSent) {
      res.status(500).json({ error: message })
    } else {
      try {
        writeEvent(res, { type: 'error', message })
        res.end()
      } catch {
        /* connexion fermée */
      }
    }
  } finally {
    if (openKey !== null) opensInFlight.delete(openKey)
  }
})

// ── Compaction ─────────────────────────────────────────────────────────────
// Même mécanique que le /compact de Claude Code : passe mémoire PUIS résumé, qui
// remplace les messages couverts dans les prochains payloads. La passe mémoire
// utilise les outils en mode complet ; en mode simple, c'est le serveur qui écrit
// (le modèle se contente de lister des faits en texte).

const COMPACT_MIN_MESSAGES = 6
// Six et non quatre : la passe mémoire sous garde-fou coûte un aller-retour de
// lecture par fichier existant touché (memory_read puis memory_update/append).
const COMPACT_MAX_ITERATIONS = 6
// Garde-fou d'horloge d'une compaction : au-delà, l'appel backend est abandonné
// et le verrou compactionsInFlight se libère (10 min — large, jamais infini).
const COMPACT_TIMEOUT_MS = 10 * 60_000
const COMPACT_KEEP_RECENT = 4 // messages récents laissés « vivants » après compaction
const COMPACT_SUMMARY_MAX_CHARS = 20000 // un résumé est un résumé, pas une archive

// ── Mode simple : la mémoire est écrite par le SERVEUR ─────────────────────
// Le petit modèle n'a aucun outil : on lui demande une simple liste de faits,
// en texte, et c'est Hanami qui la range dans le fichier mémoire.
const FACTS_DIRECTIVE =
  'List the important durable facts from this conversation worth remembering long-term, one per line, ' +
  'each line starting with "FACT: " — nothing else.'
const AUTO_MEMORY_FILE = 'auto-memory.md'
const AUTO_MEMORY_INDEX_LINE = `- [Remembered facts](${AUTO_MEMORY_FILE}) — facts extracted automatically during compaction`
const AUTO_MEMORY_MAX_FACTS = 20 // garde-fou : un modèle bavard ne noie pas la mémoire
const AUTO_MEMORY_MAX_CHARS = 500 // par fait

// Puce et gras optionnels autour du marqueur : les petits modèles écrivent
// volontiers « - **FACT:** … » malgré la consigne.
const FACT_LINE = /^[\s>*_-]*FACT[\s*_]*:[\s*_]*(.+)$/i

/** Faits extraits d'une réponse en texte libre (liste vide si le modèle n'a rien suivi). */
function parseFacts(text: string): string[] {
  const facts: string[] = []
  for (const line of text.split('\n')) {
    const m = FACT_LINE.exec(line)
    if (!m) continue
    const fact = m[1].replace(/[*_\s]+$/, '').trim()
    if (fact) facts.push(fact.slice(0, AUTO_MEMORY_MAX_CHARS))
    if (facts.length >= AUTO_MEMORY_MAX_FACTS) break
  }
  return facts
}

/** Ajoute les faits datés au fichier mémoire auto + tient l'index MEMORY.md à jour. */
function appendAutoFacts(charId: string, facts: string[]): void {
  const date = new Date().toISOString().slice(0, 10)
  const existing =
    readMemoryFile(charId, AUTO_MEMORY_FILE) ??
    '# Remembered facts\n\nExtracted automatically from conversations during compaction (simple mode).\n'
  const lines = facts.map((f) => `- **${date}** — ${f}`).join('\n')
  writeMemoryFile(charId, AUTO_MEMORY_FILE, existing.replace(/\n*$/, '\n') + '\n' + lines + '\n')
  // Upsert de la ligne d'index. index === null : MEMORY.md illisible — on
  // n'écrit PAS un index neuf par-dessus un fichier peut-être existant.
  const index = readMemoryFile(charId, 'MEMORY.md')
  if (index !== null && !index.includes(`](${AUTO_MEMORY_FILE})`)) {
    writeMemoryFile(charId, 'MEMORY.md', index.replace(/\n*$/, '\n') + AUTO_MEMORY_INDEX_LINE + '\n')
  }
}

// Verrou par chat : jamais deux compactions concurrentes sur le même fichier.
const compactionsInFlight = new Set<string>()

// memoryTools : la consigne « sers-toi des outils mémoire » n'a de sens que si
// des outils sont réellement exposés (jamais en mode simple).
function compactDirective(hasPrevSummary: boolean, memoryTools: boolean, instruction: string): string {
  let d =
    '[HANAMI COMPACTION]\n' +
    'The conversation above is about to be condensed to free up context. Write ONE summary that will ' +
    'replace these messages in your future context.\n' +
    '- Write the summary in the same language as the conversation.\n' +
    '- Preserve: key events, facts learned, decisions, promises, emotional beats, running jokes, and the current situation.\n'
  if (hasPrevSummary) {
    d +=
      '- A previous conversation summary is already in your system context: merge it with the new messages into one coherent, updated summary.\n'
  }
  if (memoryTools) {
    d +=
      '- BEFORE writing the summary, persist any durable facts worth remembering beyond this conversation: ' +
      'memory_read an existing memory file before memory_update (complete merged content), ' +
      'memory_append a fact to an existing file, memory_save only brand-new topics.\n'
  }
  if (instruction) d += `- User instruction for this compaction: ${instruction}\n`
  d += 'Reply with ONLY the summary text (no preamble, no emotion tag).'
  return d
}

async function runCompaction(
  characterId: string,
  chatId: string,
  instruction: string,
): Promise<{ summary: string; summaryUpto: number; compacted: number }> {
  const settings = loadSettings()
  const character = getCharacter(characterId)
  if (!character) throw new Error(`Personnage introuvable : ${characterId}`)
  const { meta, messages: history } = readChat(characterId, chatId)
  const prevUpto = meta.summary ? Math.min(meta.summaryUpto ?? 0, history.length) : 0
  const candidates = history.slice(prevUpto)
  if (candidates.length < COMPACT_MIN_MESSAGES) {
    throw new Error(`Rien à compacter (moins de ${COMPACT_MIN_MESSAGES} messages depuis le dernier résumé)`)
  }

  // Mode simple : pas de passe agentique, donc rien à annoncer sur les outils mémoire.
  const simple = settings.modelMode === 'simple'
  const names = macroNamesFor(character.name, settings)
  let systemText = character.systemPrompt
  if (settings.memoryEnabled) systemText += buildMemoryBlock(characterId, simple)
  if (meta.summary) systemText += summaryBlock(meta.summary)
  const directive = compactDirective(!!meta.summary, settings.memoryEnabled && !simple, instruction)

  // Prompt + complétion doivent tenir dans la fenêtre du modèle : les backends
  // stricts (vLLM, OpenAI…) rejettent sinon, et les permissifs (KoboldCpp)
  // tronqueraient par l'avant SANS erreur — résumé partiel, contexte perdu.
  const window = settings.contextSize > 0 ? settings.contextSize : 32768
  // Budget de sortie généreux (modèles « thinking ») mais jamais plus du tiers
  // de la fenêtre.
  const completionBudget = Math.min(Math.max(settings.maxTokens, 8192), Math.max(1024, Math.floor(window / 3)))
  let promptBudget =
    window - completionBudget - estimateTokens(systemText) - estimateTokens(directive) - 512 // marge outils

  // La tranche compactée part du plus ANCIEN et s'arrête au budget — les
  // messages récents restent vivants (continuité immédiate, comme /compact).
  // summaryUpto ne couvre QUE ce qui a réellement été soumis au modèle.
  const maxTake = Math.max(0, candidates.length - COMPACT_KEEP_RECENT)
  let take = 0
  while (take < maxTake) {
    const cost = estimateTokens(candidates[take])
    if (cost > promptBudget) break
    promptBudget -= cost
    take++
  }
  if (take < 1) {
    throw new Error('Fenêtre trop petite pour compacter — augmentez « Taille de contexte du modèle »')
  }
  const slice = candidates.slice(0, take)
  const upto = prevUpto + take

  // Mêmes macros que le chat : le modèle qui résume lit le personnage sous son
  // nom, pas sous « {{char}} ».
  const baseMessages: unknown[] = [
    { role: 'system', content: substituteMacros(systemText, names) },
    ...slice.map((m) => ({ role: m.role, content: substituteMacros(m.content, names) })),
  ]
  const messages: unknown[] = [...baseMessages, { role: 'user', content: directive }]
  const tools = settings.memoryEnabled && !simple ? memoryToolDefs : []
  const abort = new AbortController()
  // Garde-fou d'horloge : sans lui, un backend qui ne répond jamais laissait le
  // verrou compactionsInFlight posé pour toute la vie du processus (l'appelant
  // ne peut pas annuler — le résumé doit persister même si le client est parti,
  // choix assumé). Large : une compaction est lente par nature. Pas de clear :
  // aborter un stream déjà terminé est un no-op, et unref n'empêche pas l'arrêt.
  const timer = setTimeout(() => abort.abort(), COMPACT_TIMEOUT_MS)
  timer.unref()
  const compactSettings: Settings = { ...settings, maxTokens: completionBudget }

  let summary = ''
  let lastFinish = ''
  // Faits collectés en mode simple — écrits UNIQUEMENT après un résumé réussi :
  // si la compaction échoue puis est relancée, les mêmes faits repasseraient et
  // se dupliqueraient dans le fichier mémoire.
  let pendingFacts: string[] = []

  if (simple) {
    // (a) Passe mémoire SANS outils : le modèle liste des faits, le serveur les
    // range. Une réponse hors format ne donne aucun fait — on continue sans bruit.
    if (settings.memoryEnabled) {
      try {
        const factsResult = await streamChatCompletion({
          settings: compactSettings,
          messages: [...baseMessages, { role: 'user', content: FACTS_DIRECTIVE }],
          signal: abort.signal,
          onDelta: () => {},
        })
        pendingFacts = parseFacts(factsResult.content)
      } catch (e) {
        // La mémoire est un bonus : l'échec ne doit pas emporter le résumé
        // (si le backend est vraiment tombé, l'appel suivant le dira).
        console.warn('[compact:facts]', e instanceof Error ? e.message : String(e))
      }
    }
    // (b) Résumé, toujours sans outils.
    const result = await streamChatCompletion({
      settings: compactSettings,
      messages,
      signal: abort.signal,
      onDelta: () => {},
    })
    lastFinish = result.finishReason
    summary = result.content.trim()
  } else {
    // Boucle agentique silencieuse (partagée avec le chat, cf. runToolLoop) :
    // le résumé = le texte du DERNIER appel — celui sans appels d'outils, ou le
    // dernier forcé sans outils quand le budget est épuisé.
    const mem = createMemorySession() // lectures mémoire de CETTE compaction (garde-fou)
    const { last } = await runToolLoop(
      characterId,
      settings,
      messages,
      COMPACT_MAX_ITERATIONS,
      toolNamesOf(tools),
      mem,
      async (withTools) => {
        const result = await streamChatCompletion({
          settings: compactSettings,
          messages,
          tools: withTools && tools.length > 0 ? tools : undefined,
          signal: abort.signal,
          onDelta: () => {},
        })
        lastFinish = result.finishReason
        return result
      },
    )
    summary = last.content.trim()
  }
  if (!summary) {
    throw new Error(
      `Le modèle n'a pas produit de résumé (fin de génération : ${lastFinish || 'inconnue'} — ` +
        `pensez à augmenter « Tokens max » ou la fenêtre du backend)`,
    )
  }
  summary = summary.slice(0, COMPACT_SUMMARY_MAX_CHARS)

  // Le résumé a réussi : les faits du mode simple peuvent être rangés sans
  // risque de doublon au prochain essai.
  if (pendingFacts.length > 0) appendAutoFacts(characterId, pendingFacts)

  updateChatHeader(characterId, chatId, { summary, summaryUpto: upto })
  return { summary, summaryUpto: upto, compacted: upto - prevUpto }
}

// POST /api/chat/compact {characterId, chatId, instruction?} — compaction manuelle ou auto.
chatRouter.post('/api/chat/compact', async (req, res) => {
  const body = (req.body ?? {}) as { characterId?: unknown; chatId?: unknown; instruction?: unknown }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const instruction = typeof body.instruction === 'string' ? body.instruction.trim().slice(0, 2000) : ''
  if (!characterId || !chatId) {
    res.status(400).json({ error: 'characterId et chatId sont requis' })
    return
  }
  try {
    readChat(characterId, chatId)
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }
  const lockKey = `${characterId}/${chatId}`
  if (compactionsInFlight.has(lockKey)) {
    res.status(409).json({ error: 'Compaction déjà en cours pour cette conversation' })
    return
  }
  compactionsInFlight.add(lockKey)
  try {
    res.json(await runCompaction(characterId, chatId, instruction))
  } catch (e) {
    res.status(500).json({ error: e instanceof Error ? e.message : String(e) })
  } finally {
    compactionsInFlight.delete(lockKey)
  }
})

// PUT /api/chat/message {characterId, chatId, index, content} — édition d'un message
// en place (l'émotion est re-détectée pour les messages de l'assistant).
//
// Une réponse à variantes édite CELLE QUI EST AFFICHÉE et perd les autres :
// écrire soi-même le texte est un choix définitif, on ne feuillette plus après.
chatRouter.put('/api/chat/message', (req, res) => {
  const body = (req.body ?? {}) as {
    characterId?: unknown
    chatId?: unknown
    index?: unknown
    content?: unknown
  }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const index = typeof body.index === 'number' && Number.isInteger(body.index) ? body.index : -1
  const content = typeof body.content === 'string' ? body.content : ''
  if (!characterId || !chatId || index < 0 || !content.trim()) {
    res.status(400).json({ error: 'characterId, chatId, index et content sont requis' })
    return
  }
  let count: number
  try {
    count = readChat(characterId, chatId).messages.length
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }
  if (index >= count) {
    res.status(404).json({ error: `Message introuvable : ${index}` })
    return
  }
  let updated: ChatMessage | null = null
  rewriteChatMessages(characterId, chatId, (msgs) => {
    const msg: ChatMessage = { ...pruneVariants(msgs[index]), content }
    if (msg.role === 'assistant') {
      delete msg.emotion
      const emotion = firstEmotionTag(content)
      if (emotion) msg.emotion = emotion
    }
    msgs[index] = msg
    updated = msg
    return msgs
  })
  res.json({ index, message: updated })
})

// PUT /api/chat/variant {characterId, chatId, index, variant} — change la variante
// AFFICHÉE d'une réponse (« swipe »). Le corps du message recopie la variante
// choisie : le payload du prochain envoi, l'export .md, la voix, la copie et
// l'émotion du visage la suivent aussitôt, sans rien savoir des variantes.
//
// AUCUN message n'est ajouté ni retiré : l'index reste celui du message, et les
// repères qui comptent des messages (épingle, summaryUpto) sont hors sujet ici.
chatRouter.put('/api/chat/variant', (req, res) => {
  const body = (req.body ?? {}) as {
    characterId?: unknown
    chatId?: unknown
    index?: unknown
    variant?: unknown
  }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const index = typeof body.index === 'number' && Number.isInteger(body.index) ? body.index : -1
  const variant = typeof body.variant === 'number' && Number.isInteger(body.variant) ? body.variant : -1
  if (!characterId || !chatId || index < 0 || variant < 0) {
    res.status(400).json({ error: 'characterId, chatId, index et variant (entiers ≥ 0) sont requis' })
    return
  }
  let messages: ChatMessage[]
  try {
    messages = readChat(characterId, chatId).messages
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }
  if (index >= messages.length) {
    res.status(404).json({ error: `Message introuvable : ${index}` })
    return
  }
  const target = messages[index]
  if (!target.variants || target.variants.length < 2) {
    res.status(400).json({ error: `Ce message n'a pas de variantes : ${index}` })
    return
  }
  if (variant >= target.variants.length) {
    res.status(404).json({ error: `Variante introuvable : ${variant}` })
    return
  }
  let updated: ChatMessage | null = null
  rewriteChatMessages(characterId, chatId, (msgs) => {
    const msg = msgs[index]
    // Le fil a pu bouger entre la lecture et la réécriture : sans variantes (ou
    // moins nombreuses), on ne touche à rien.
    if (!msg || !msg.variants || variant >= msg.variants.length) return msgs
    updated = withVariants(msg, msg.variants, variant)
    msgs[index] = updated
    return msgs
  })
  if (updated === null) {
    res.status(409).json({ error: 'La conversation a changé — variante introuvable' })
    return
  }
  res.json({ index, message: updated })
})

// DELETE /api/chat/message {characterId, chatId, index} — retire UN message du fil.
// Le pendant de l'édition : « Régénérer » ne sait défaire que la dernière réponse,
// une bulle ratée au milieu du fil n'avait aucune sortie.
//
// Les deux repères de l'en-tête qui comptent des messages doivent suivre le
// décalage, sans quoi le prochain envoi partirait de travers :
//   · `pinned` — l'ordinal épinglé (le message supprimé perd son épingle) ;
//   · `summaryUpto` — la frontière du résumé de compaction, qui décide de la
//     tranche d'historique envoyée au modèle.
chatRouter.delete('/api/chat/message', (req, res) => {
  const body = (req.body ?? {}) as { characterId?: unknown; chatId?: unknown; index?: unknown }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const index = typeof body.index === 'number' && Number.isInteger(body.index) ? body.index : -1
  if (!characterId || !chatId || index < 0) {
    res.status(400).json({ error: 'characterId, chatId et index sont requis' })
    return
  }
  let meta
  try {
    meta = readChat(characterId, chatId).meta
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }
  if (index >= meta.messageCount) {
    res.status(404).json({ error: `Message introuvable : ${index}` })
    return
  }
  rewriteChatMessages(characterId, chatId, (msgs) => msgs.filter((_, i) => i !== index))
  // Épingle et frontière de résumé recalées sur le fil raccourci.
  const pinned =
    typeof meta.pinned !== 'number' ? undefined : meta.pinned === index ? undefined : meta.pinned > index ? meta.pinned - 1 : meta.pinned
  const summaryUpto =
    meta.summary && typeof meta.summaryUpto === 'number' && meta.summaryUpto > index
      ? meta.summaryUpto - 1
      : meta.summaryUpto
  if (pinned !== meta.pinned || summaryUpto !== meta.summaryUpto) {
    updateChatHeader(characterId, chatId, {
      pinned,
      ...(meta.summary ? { summaryUpto } : {}),
    })
  }
  res.json({ index, messageCount: meta.messageCount - 1, pinned: pinned ?? null })
})

// PUT /api/chat/summary {characterId, chatId, summary} — édition (ou retrait) du résumé.
chatRouter.put('/api/chat/summary', (req, res) => {
  const body = (req.body ?? {}) as { characterId?: unknown; chatId?: unknown; summary?: unknown }
  const characterId = typeof body.characterId === 'string' ? body.characterId : ''
  const chatId = typeof body.chatId === 'string' ? body.chatId : ''
  const summary = typeof body.summary === 'string' ? body.summary : null
  if (!characterId || !chatId || summary === null) {
    res.status(400).json({ error: 'characterId, chatId et summary sont requis' })
    return
  }
  let meta
  try {
    meta = readChat(characterId, chatId).meta
  } catch {
    res.status(404).json({ error: `Chat introuvable : ${chatId}` })
    return
  }
  if (!meta.summary) {
    res.status(400).json({ error: "Ce chat n'a pas encore de résumé de compaction" })
    return
  }
  // Résumé vidé = compaction annulée : l'historique complet repart dans le payload.
  if (summary.trim() === '') {
    updateChatHeader(characterId, chatId, { summary: undefined, summaryUpto: undefined })
    res.json({ summary: '', summaryUpto: 0 })
    return
  }
  const capped = summary.slice(0, COMPACT_SUMMARY_MAX_CHARS)
  updateChatHeader(characterId, chatId, { summary: capped, summaryUpto: meta.summaryUpto ?? 0 })
  res.json({ summary: capped, summaryUpto: meta.summaryUpto ?? 0 })
})

