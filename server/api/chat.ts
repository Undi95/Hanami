// ── Images (modèles à vision) ──────────────────────────────────────────────
// Un message porteur d'images part en content OpenAI multimodal ; le texte, lui,
// reste une simple string dans le fichier de chat (ChatMessage.content).

/** Partie d'un content multimodal OpenAI. */
export type ContentPart = { type: 'text'; text: string } | { type: 'image_url'; image_url: { url: string } }

/** Content OpenAI d'un message : le texte seul, ou le tableau multimodal si des images l'accompagnent. */
function messageContent(m: ChatMessage): string | ContentPart[] {
  return m.images && m.images.length > 0 ? multimodalContent(m.content, m.images) : m.content
}

/** [texte ?, image, image…] — la partie texte est omise quand il n'y a pas de texte. */
export function multimodalContent(text: string, images: string[]): ContentPart[] {
  const parts: ContentPart[] = []
  if (text) parts.push({ type: 'text', text })
  for (const url of images) parts.push({ type: 'image_url', image_url: { url } })
  return parts
}

// ── Macros des cards ───────────────────────────────────────────────────────
// {{char}} / {{user}} (et <BOT> / <USER>) sont substitués ICI, à la
// construction du payload : les fichiers du disque gardent leurs macros, seul
// ce qui PART vers le modèle est résolu. Le prompt du personnage renvoyé à
// l'inspecteur reste donc la source, éditable telle quelle.

/** Noms substitués : le personnage, et l'utilisateur tel que sa persona le nomme. */
function macroNamesFor(characterName: string, settings: Settings): MacroNames {
  return { char: characterName, user: userName(settings.personaName) }
}

/**
 * Bloc persona : qui est l'utilisateur, tel qu'il s'est décrit dans les
 * réglages. Faits bruts (en anglais, langue de travail des prompts), AUCUNE
 * directive ajoutée — comme le bloc heure et les notes de scène. Les deux
 * champs sont indépendants : un nom seul, une description seule, ou les deux.
 */
function personaBlock(name: string, description: string): string {
  let block = '\n\n## The user (persona, set by the user in Hanami settings)\n'
  if (name) block += `The user's name is ${name}.\n`
  if (description) block += `${description}\n`
  return block
}

/** Substitution dans un content OpenAI : texte seul, ou parties texte d'un multimodal. */
function subContent(content: string | ContentPart[], names: MacroNames): string | ContentPart[] {
  if (typeof content === 'string') return substituteMacros(content, names)
  return content.map((p) => (p.type === 'text' ? { ...p, text: substituteMacros(p.text, names) } : p))
}

/** Bloc résumé de compaction injecté dans le system prompt (visible dans l'inspecteur). */
function summaryBlock(summary: string): string {
  return `\n\n## Conversation summary (auto-generated by Hanami compaction — earlier messages were condensed into this)\n\n${summary}`
}

/**
 * Bloc notes de scène de la conversation : le texte de l'utilisateur, RIEN de plus
 * (pas de directive ajoutée). Champ vide = bloc absent, donc zéro injection.
 */
function sceneNotesBlock(notes: string): string {
  return `\n\n## Scene notes (set by the user for this conversation)\n\n${notes}`
}

/** Plafond des notes de scène — c'est une note d'ambiance, pas un second prompt. */
const SCENE_NOTES_MAX_CHARS = 2000

// Coût forfaitaire d'une image. Une data URL pèse des centaines de milliers de
// caractères pour quelques centaines de tokens réels : la compter au caractère
// ferait exploser la jauge de contexte ET le budget de compaction.
const IMAGE_TOKENS = 800

/**
 * Copie de la valeur où chaque data URL d'image devient un jeton court, plus le
 * nombre d'images rencontrées. Vaut pour les deux formes : le `image_url.url`
 * d'un content multimodal et le `images[]` d'un ChatMessage brut.
 */
function withoutImageData(value: unknown): { lean: unknown; images: number } {
  let images = 0
  const walk = (v: unknown): unknown => {
    if (typeof v === 'string') {
      if (!v.startsWith('data:image/')) return v
      images++
      return '[image]'
    }
    if (Array.isArray(v)) return v.map(walk)
    if (v !== null && typeof v === 'object') {
      const out: Record<string, unknown> = {}
      for (const [k, child] of Object.entries(v as Record<string, unknown>)) out[k] = walk(child)
      return out
    }
    return v
  }
  const lean = walk(value)
  return { lean, images }
}

/** Estimation grossière du volume de tokens (~4 caractères/token sur le JSON, forfait par image). */
function estimateTokens(value: unknown): number {
  const { lean, images } = withoutImageData(value)
  return Math.ceil(JSON.stringify(lean).length / 4) + images * IMAGE_TOKENS
}

/** Écart humanisé entre deux messages (en anglais : langue de travail des prompts). */
function humanizeGap(ms: number): string {
  const min = Math.floor(ms / 60000)
  if (min < 1) return 'less than a minute'
  if (min < 60) return `${min} minute${min > 1 ? 's' : ''}`
  const h = Math.floor(min / 60)
  if (h < 48) return `${h} hour${h > 1 ? 's' : ''}`
  return `${Math.floor(h / 24)} days`
}

// Bloc temporel : le personnage sait QUAND on lui parle (matin/soir, retour
// après des jours…). Faits bruts en anglais — le modèle les exprime dans la
// langue de la conversation. Visible dans l'inspecteur comme tout le reste.
const WEEKDAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']

function timeBlock(lastMessageTs: string | null): string {
  const now = new Date()
  const pad = (n: number) => String(n).padStart(2, '0')
  // Timezone NOMMÉE (et non « user's local time ») : un ancrage explicite que
  // le modèle peut vérifier, au lieu d'une notion à deviner.
  const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || 'local time'
  let block =
    '\n\n## Current date and time (auto-injected by Hanami — the only authoritative source)\n' +
    `Now: ${WEEKDAYS[now.getDay()]} ${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}, ` +
    `${pad(now.getHours())}:${pad(now.getMinutes())} (${tz}, the user's local time).\n`
  if (lastMessageTs) {
    const gap = now.getTime() - new Date(lastMessageTs).getTime()
    if (Number.isFinite(gap) && gap >= 0) {
      block += `Time since the previous message in this conversation: ${humanizeGap(gap)}.\n`
    }
  }
  // L'ancienne consigne « never recite it » faisait échouer la question directe
  // « quelle heure est-il ? » : le modèle généralisait « ne pas réciter » à
  // « ne pas répondre ». D'où l'autorisation explicite ci-dessous, et la phrase
  // d'autorité : les modèles locaux ont tendance à répondre une date de leur
  // données d'entraînement si on ne leur impose pas celle d'ici.
  block +=
    'Your training data does not know the current date or time — trust ONLY the values above, never a date you may "remember".\n' +
    'If the user asks what day, date or time it is, answer directly and exactly with those values, ' +
    'in the language of the conversation. Otherwise let them shape your replies naturally ' +
    '(greetings, time of day, absences) without reciting them.\n'
  return block
}

/**
 * Construit le payload EXACT envoyé au backend (aussi renvoyé tel quel par
 * /api/prompt-preview, et réutilisé par le moteur de messages spontanés).
 *
 * Le texte système est rendu en DEUX morceaux en plus du tout :
 * `characterPrompt` (le prompt du personnage, celui qui s'écrit et se corrige)
 * et `injected` (ce que Hanami ajoute : mémoire, résumé, notes de scène,
 * heure). L'inspecteur s'en sert pour rendre le premier ÉDITABLE sur place,
 * sans avoir à deviner où finit l'un et où commence l'autre.
 *
 * Nuance depuis les macros : ces deux morceaux sont la SOURCE, macros comprises
 * ({{char}}, {{user}}) — `systemText` et `payload`, eux, sont résolus. Écrire
 * l'un par-dessus l'autre figerait les macros dans le fichier du personnage.
 */
export function buildPayload(
  characterId: string,
  chatId: string,
  settings: Settings,
  // string = message (ou consigne) purement textuel ; tableau = message courant
  // accompagné d'images (content multimodal OpenAI).
  pendingUserContent?: string | ContentPart[],
  // Régénération : la réponse à refaire est encore DANS le fichier (elle y reste,
  // elle va devenir une variante) — elle est simplement retirée de l'historique
  // envoyé, sinon le modèle réécrirait par-dessus sa propre copie.
  omitLastMessage = false,
): { systemText: string; characterPrompt: string; injected: string; payload: BackendPayload } {
  const character = getCharacter(characterId)
  if (!character) throw new Error(`Personnage introuvable : ${characterId}`)
  const characterPrompt = character.systemPrompt
  let injected = ''
  // La persona vient EN TÊTE des blocs ajoutés : savoir à qui l'on parle
  // précède ce dont on se souvient de lui.
  const personaName = settings.personaName.trim()
  const personaDescription = settings.personaDescription.trim()
  if (personaName || personaDescription) injected += personaBlock(personaName, personaDescription)
  if (settings.memoryEnabled) injected += buildMemoryBlock(characterId, settings.modelMode === 'simple')

  const { meta, messages: all } = readChat(characterId, chatId)
  const history = omitLastMessage ? all.slice(0, -1) : all
  // Conversation compactée : le résumé (dans le system) remplace les messages qu'il couvre.
  const upto = meta.summary ? Math.min(meta.summaryUpto ?? 0, history.length) : 0
  if (meta.summary) injected += summaryBlock(meta.summary)
  if (meta.sceneNotes) injected += sceneNotesBlock(meta.sceneNotes)
  if (settings.timeAwareness) {
    injected += timeBlock(history.length > 0 ? history[history.length - 1].ts : null)
  }
  // Macros résolues sur TOUT ce qui part : le texte système (prompt du
  // personnage ET blocs ajoutés — une note de scène peut dire « {{char}} »),
  // l'historique et le message courant. `characterPrompt` reste brut plus bas :
  // c'est la source que l'inspecteur rend éditable.
  const names = macroNamesFor(character.name, settings)
  const systemText = substituteMacros(characterPrompt + injected, names)
  const live = history.slice(upto)
  const recent = settings.maxHistoryMessages > 0 ? live.slice(-settings.maxHistoryMessages) : []
  const messages: unknown[] = [
    { role: 'system', content: systemText },
    // Un message d'historique porteur d'images repart en multimodal : le modèle
    // à vision revoit donc les images des tours précédents.
    ...recent.map((m) => ({ role: m.role, content: subContent(messageContent(m), names) })),
  ]
  if (pendingUserContent !== undefined) {
    messages.push({ role: 'user', content: subContent(pendingUserContent, names) })
  }

  // Mode simple : AUCUN outil n'est exposé (le tool-calling est le talon d'Achille
  // des petits modèles). Le bloc mémoire, lui, reste injecté — il se lit sans outil.
  const tools: unknown[] =
    settings.modelMode === 'simple'
      ? []
      : [
          // chat_search voyage avec la mémoire : c'est le même « souvenir de l'autre ».
          ...(settings.memoryEnabled ? [...memoryToolDefs, ...chatToolDefs] : []),
          ...(settings.fileToolsEnabled ? fileToolDefs : []),
          ...(settings.webSearchEnabled ? webSearchToolDefs : []),
        ]
  const payload: BackendPayload = {
    messages,
    model: settings.model,
    temperature: settings.temperature,
    max_tokens: settings.maxTokens,
  }
  if (tools.length > 0) payload.tools = tools
  return { systemText, characterPrompt, injected, payload }
}

// ── Impersonate ─────────────────────────────────────────────────────────────
// « Écrire à la place de l'utilisateur » — PAS un simple ajout en fin du prompt
// du personnage (le piège de SillyTavern, qui laisse la persona du perso
// dominer) : le system prompt est ici reconstruit avec l'UTILISATEUR comme
// locuteur et {{char}} comme interlocuteur, et l'historique est ÉCHANGÉ
// (assistant ↔ user) — le modèle, qui complète toujours le rôle « assistant »,
// écrit donc naturellement dans SA voix à lui. characterPrompt (les
// instructions de rôle du personnage) n'entre JAMAIS dans ce payload : c'est
// justement lui qu'il faut faire taire pour que la persona utilisateur tienne.

const IMPERSONATE_LENGTH_SAMPLE = 12 // derniers tours utilisateur considérés représentatifs

/** Longueur (caractères) typique des messages récents de l'utilisateur — null si aucun. */
function typicalUserLength(history: ChatMessage[]): number | null {
  const lens = history
    .filter((m) => m.role === 'user' && m.content.trim())
    .slice(-IMPERSONATE_LENGTH_SAMPLE)
    .map((m) => m.content.trim().length)
  if (lens.length === 0) return null
  return Math.round(lens.reduce((a, b) => a + b, 0) / lens.length)
}

/** System prompt d'impersonation : l'utilisateur EST le locuteur, {{char}} est l'autre. */
function impersonateSystemPrompt(
  characterName: string,
  personaName: string,
  personaDescription: string,
  typicalLen: number | null,
): string {
  const who = personaName || 'the user'
  let block = `You are ${who}, a real person in an ongoing conversation with ${characterName}.\n`
  if (personaDescription) block += `About you: ${personaDescription}\n`
  block +=
    `\nWrite YOUR OWN next message to ${characterName} — from your own point of view, in your own voice, ` +
    `never theirs. Below, ${characterName}'s turns are tagged "user" and yours are tagged "assistant", so that ` +
    `you naturally continue as yourself when completing the assistant turn.\n` +
    `Match your own tone, habits and phrasing as shown earlier in the conversation.`
  if (typicalLen !== null) {
    block += ` Your messages usually run about ${typicalLen} characters long — stay close to that, don't ramble.`
  }
  block += ' Reply with ONLY that message: no narration, no emotion tags, no meta-commentary.'
  return block
}

/**
 * Payload d'impersonation : réutilise les blocs neutres de buildPayload
 * (résumé, notes de scène, heure — de simples faits, jamais des instructions
 * de rôle) mais jamais characterPrompt, et échange les rôles de l'historique.
 * Aucun outil exposé : impersonate écrit une réplique, jamais une action.
 */
function buildImpersonatePayload(
  characterId: string,
  chatId: string,
  settings: Settings,
): { payload: BackendPayload } {
  const character = getCharacter(characterId)
  if (!character) throw new Error(`Personnage introuvable : ${characterId}`)
  const { meta, messages: all } = readChat(characterId, chatId)
  const names = macroNamesFor(character.name, settings)

  let injected = ''
  if (meta.summary) injected += summaryBlock(meta.summary)
  if (meta.sceneNotes) injected += sceneNotesBlock(meta.sceneNotes)
  if (settings.timeAwareness) injected += timeBlock(all.length > 0 ? all[all.length - 1].ts : null)

  const base = impersonateSystemPrompt(
    character.name,
    settings.personaName.trim(),
    settings.personaDescription.trim(),
    typicalUserLength(all),
  )
  const systemText = substituteMacros(base + injected, names)

  const upto = meta.summary ? Math.min(meta.summaryUpto ?? 0, all.length) : 0
  const live = all.slice(upto)
  const recent = settings.maxHistoryMessages > 0 ? live.slice(-settings.maxHistoryMessages) : []
  const messages: unknown[] = [
    { role: 'system', content: systemText },
    // Perspective inversée : le tour de {{char}} devient "user", celui de
    // l'utilisateur devient "assistant" — voir le commentaire de section plus haut.
    ...recent.map((m) => ({
      role: m.role === 'assistant' ? 'user' : 'assistant',
      content: subContent(messageContent(m), names),
    })),
  ]
  return {
    payload: { messages, model: settings.model, temperature: settings.temperature, max_tokens: settings.maxTokens },
  }
}

function toAssistantMessage(text: string, thinking?: string): ChatMessage {
  const emotion = firstEmotionTag(text)
  const msg: ChatMessage = { role: 'assistant', content: text, ts: new Date().toISOString() }
  if (emotion) msg.emotion = emotion
  if (thinking) msg.thinking = thinking
  return msg
}

// Résultat plafonné pour la PERSISTANCE : un read_file peut faire 256 Ko et le
// .jsonl ne doit pas gonfler — la puce dépliée n'a besoin que du début du
// résultat. En session (event SSE), le client garde le résultat intégral.
const TRACE_RESULT_CAP = 2048
function cappedTraceResult(result: string): string {
  return result.length > TRACE_RESULT_CAP ? result.slice(0, TRACE_RESULT_CAP) + '…' : result
}

// ── Variantes de réponse ───────────────────────────────────────────────────
// « Régénérer » n'écrase plus la dernière réponse : elle devient une variante du
// MÊME message, la nouvelle s'ajoute à côté et devient celle qui est affichée.
// Aucun message n'est créé ni retiré au passage — tout tient dans la ligne.
// L'invariant (corps du message = variante affichée) se pose ici et se rejoue à
// la lecture (lib/storage.ts).

/**
 * Plafond de variantes gardées sur un message. Au-delà, la PLUS ANCIENNE
 * s'efface : une ligne de .jsonl ne doit pas enfler sans fin sous les clics.
 * L'élagage du prochain message utilisateur fait le reste du ménage.
 */
const MAX_VARIANTS = 12

/** Le corps d'un message, isolé — c'est exactement ce qu'une variante porte. */
function bodyOf(m: ChatMessage): MessageVariant {
  return {
    content: m.content,
    ts: m.ts,
    ...(m.emotion ? { emotion: m.emotion } : {}),
    ...(m.thinking ? { thinking: m.thinking } : {}),
    ...(m.tools && m.tools.length > 0 ? { tools: m.tools } : {}),
  }
}

/** Variantes d'un message — son propre corps quand il n'en porte aucune. */
function variantsOf(m: ChatMessage): MessageVariant[] {
  return m.variants && m.variants.length >= 2 ? m.variants : [bodyOf(m)]
}

/** Message reconstruit autour de la variante `index` (l'invariant du format). */
function withVariants(m: ChatMessage, variants: MessageVariant[], index: number): ChatMessage {
  const active = variants[index]
  const out: ChatMessage = { ...m, content: active.content, ts: active.ts }
  delete out.emotion
  if (active.emotion) out.emotion = active.emotion
  delete out.thinking
  if (active.thinking) out.thinking = active.thinking
  delete out.tools
  if (active.tools) out.tools = active.tools
  if (variants.length >= 2) {
    out.variants = variants
    out.variant = index
  } else {
    delete out.variants
    delete out.variant
  }
  return out
}

/**
 * ÉLAGAGE : la variante affichée reste, les autres disparaissent — le corps du
 * message ne bouge pas d'un caractère (il la recopiait déjà). Appliqué dès que
 * le fil AVANCE (nouveau message de l'utilisateur) ou qu'une réponse est éditée
 * à la main : feuilleter sert à choisir avant de continuer, pas à emporter
 * quatre versions du passé dans toute la conversation.
 */
function pruneVariants(m: ChatMessage): ChatMessage {
  if (m.variants === undefined && m.variant === undefined) return m
  const out = { ...m }
  delete out.variants
  delete out.variant
  return out
}

/**
 * Registre des outils : route l'appel vers mémoire, chat ou fichiers — et
 * REVÉRIFIE les réglages. buildPayload filtre les définitions exposées, mais un
 * modèle peut halluciner un nom d'outil jamais annoncé : sans ces gardes, un
 * write_file s'exécutait même outils fichiers désactivés. Le throw est rendu au
 * modèle comme résultat d'outil (« Erreur : … ») — transparent, jamais fatal.
 */
async function executeTool(
  characterId: string,
  settings: Settings,
  name: string,
  rawArgs: string,
  mem: MemorySession,
): Promise<string> {
  let args: Record<string, unknown>
  try {
    args = rawArgs.trim() ? (JSON.parse(rawArgs) as Record<string, unknown>) : {}
  } catch {
    throw new Error(`invalid JSON arguments for ${name}`)
  }
  if ((MEMORY_TOOL_NAMES as readonly string[]).includes(name)) {
    if (!settings.memoryEnabled) throw new Error('memory tools are disabled in settings')
    return executeMemoryTool(characterId, name, args, mem)
  }
  if ((CHAT_TOOL_NAMES as readonly string[]).includes(name)) {
    if (!settings.memoryEnabled) throw new Error('memory tools are disabled in settings')
    return executeChatTool(characterId, name, args)
  }
  if ((FILE_TOOL_NAMES as readonly string[]).includes(name)) {
    if (!settings.fileToolsEnabled) throw new Error('file tools are disabled in settings')
    return executeFileTool(settings, name, args)
  }
  if ((WEB_SEARCH_TOOL_NAMES as readonly string[]).includes(name)) {
    if (!settings.webSearchEnabled) throw new Error('web search is disabled in settings')
    return executeWebSearchTool(settings, args)
  }
  throw new Error(`unknown tool: ${name}`)
}

function writeEvent(res: Response, ev: ChatEvent): void {
  res.write('data: ' + JSON.stringify(ev) + '\n\n')
}

